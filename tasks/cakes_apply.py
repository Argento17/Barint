with open(INPUT, "r", encoding="utf-8") as f:
    data = json.load(f)

# Update page copy
data["page_copy"].update(PAGE_COPY)

filled = 0
skipped_biscuit = 0
not_in_dict = []

for p in data["products"]:
    bc   = p["barcode"]
    name = p.get("name", "")

    # Always fill confidence fields for all products
    if p.get("confidence_label_he") in (None, "PENDING_COPY", ""):
        p["confidence_label_he"]   = CONF_LABEL
    if p.get("confidence_tooltip_he") in (None, "PENDING_COPY", ""):
        p["confidence_tooltip_he"] = CONF_TOOLTIP
    if p.get("confidence_sub_reason") in (None, "PENDING_COPY", ""):
        p["confidence_sub_reason"] = CONF_SUB
    if not p.get("expansion"):
        p["expansion"] = {}
    if p["expansion"].get("servingNote") in (None, "PENDING_COPY", ""):
        p["expansion"]["servingNote"] = SERVING_NOTE
    if p["expansion"].get("confidenceLabel") in (None, "PENDING_COPY", ""):
        p["expansion"]["confidenceLabel"] = CONF_LABEL

    # Check if this is a cake (non-biscuit route, non-cookie name)
    is_cake = (
        p.get("_category_routed") != "biscuit"
        and not any(k in name for k in COOKIE_KW)
    )

    if not is_cake:
        skipped_biscuit += 1
        continue

    if bc not in COPY:
        not_in_dict.append((bc, name[:60]))
        continue

    cp = COPY[bc]
    p["insightLine"]    = cp["insightLine"]
    p["rowVerdict"]     = cp["rowVerdict"]
    p["consumerTakeaway"]    = cp["consumerTakeaway"]
    p["consumerExplanation"] = cp["consumerExplanation"]
    p["bariInterpretation"]  = cp["bariInterpretation"]
    if not p.get("expansion"):
        p["expansion"] = {}
    p["expansion"]["bottomLine"] = cp["bottomLine"]
    filled += 1

with open(OUTPUT, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print(f"Done. Filled: {filled}, Biscuit/cookie (skipped): {skipped_biscuit}, Not in dict: {len(not_in_dict)}")
if not_in_dict:
    print("Missing from COPY dict:")
    for bc, name in not_in_dict:
        print(f"  {bc}  {name}")
