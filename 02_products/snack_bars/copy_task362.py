def apply(path, copy):
    d = json.load(open(path, encoding="utf-8"))
    n = 0
    for p in d["products"]:
        c = copy.get(p["barcode"])
        if not c: continue
        p["insightLine"] = c["insightLine"]
        p["rowVerdict"] = c["rowVerdict"]
        p["expansion"]["positiveSignals"] = c["positiveSignals"]
        p["expansion"]["limitingFactors"] = c["limitingFactors"]
        p["expansion"]["comparisonContext"] = c["comparisonContext"]
        n += 1
    json.dump(d, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    return n

