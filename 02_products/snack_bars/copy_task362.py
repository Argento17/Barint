ID_MAP = json.load(open(pathlib.Path(r"C:\Bari\02_products\snack_bars\_id_barcode_map.json"), encoding="utf-8"))
def to_bc(copy_dict, mapkey):
    m = ID_MAP[mapkey]
    return {m[i]: c for i, c in copy_dict.items() if i in m}
